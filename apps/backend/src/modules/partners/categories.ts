const cache = new Map<string, string>()

/** Категория по названию и комментарию товара из фида. */
export function categoryOf(title: string, comment = ""): string {
  const key = (title || "") + "\u0001" + (comment || "")
  const hit = cache.get(key)
  if (hit) return hit

  const text = (title + " " + comment).toLowerCase().replace(/ё/g, "е")
  let out = FALLBACK_CATEGORY
  for (const [cat, re] of RULES) {
    if (re.test(text)) {
      out = cat
      break
    }
  }

  if (cache.size < 20000) cache.set(key, out)
  return out
}

